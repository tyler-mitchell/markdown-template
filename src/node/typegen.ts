import { resolve } from "node:path";
import { defineFileSystemStorage, getPath, readFile } from "package-management";
import { compile } from "../core/compile.ts";
import type { loadProject } from "./config.ts";

/** Generates native ArkType contracts for direct document imports. */
export async function generateTypes(project: Awaited<ReturnType<typeof loadProject>>) {
  const { config, cwd, files } = project;
  const fs = defineFileSystemStorage({ base: cwd });
  const declarations = [];
  for (const file of files) {
    const document = compile(readFile(fs.getFilePath(file)));
    const selected = document.frontmatter.input;
    const input = selected === undefined ? "undefined" : `Schemas[${JSON.stringify(selected)}]`;
    const source = [
      "// Generated by markdown-template. Do not edit.",
      'import type { CompiledDocument, type } from "markdown-template";',
      `type Schemas = ReturnType<typeof type.module<${JSON.stringify(document.frontmatter.schema ?? {}, null, 2)}>>;`,
      `declare const document: CompiledDocument<Schemas, ${input}>;`,
      "export default document;",
      "",
    ].join("\n");
    const output = resolve(cwd, config.types?.outDir ?? ".", file.replace(/\.mdt$/, ".d.mdt.ts"));
    declarations.push({ output, source });
  }
  const manifest = ".markdown-template/types.json";
  const previous: Record<string, string> = JSON.parse((await fs.readFile(manifest)) ?? "{}");
  const next = Object.fromEntries(
    declarations.map(({ output, source }) => [getPath({ to: output, startingFrom: cwd }), source]),
  );
  for (const [file, source] of Object.entries(previous)) {
    if (!(file in next) && (await fs.readFile(file)) === source) await fs.storage.removeItem(file);
  }
  for (const [file, source] of Object.entries(next)) {
    await fs.createFile(file, source);
  }
  await fs.createFile(manifest, JSON.stringify(next, null, 2) + "\n");
  return declarations.map(({ output }) => output);
}
